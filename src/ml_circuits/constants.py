# src/ml_circuits/constants.py

"""
Общие численные константы проекта.

Здесь хранятся только константы, используемые в нескольких частях кода:
при генерации данных, обучении моделей, расчёте метрик и проверке датасетов.
Параметры конкретных экспериментов и диапазоны компонентов вынесены в config.py.
"""

from __future__ import annotations

import math


# Базовое значение seed для воспроизводимости генерации данных и экспериментов.
SEED: int = 42


# Малое число для численной устойчивости в общих вычислениях.
EPS: float = 1e-12

# Нижний порог для логарифма модуля передаточной функции:
# log_H_mag = ln(max(|H(jω)|, EPS_LOG)).
EPS_LOG: float = 1e-12

# Нижний порог для безопасного деления, например при вычислении A_out / A_in.
EPS_DIV: float = 1e-12

# Малое число для защиты частотных признаков от деления на ноль.
EPS_F: float = 1e-24

# Малое число для защиты нормировочных коэффициентов от деления на ноль.
EPS_NORM: float = 1e-14


# Эффективное сопротивление разомкнутой цепи.
OPEN_R: float = 1e30

# Минимальное допустимое значение сопротивления в численных формулах.
R_FLOOR_OHM: float = 1e-300


# Порог модуля передаточной функции для учёта фазовой ошибки.
# При |H(jω)| ниже этого значения фаза считается физически плохо определённой.
AMP_GATE: float = 0.05

# Аналогичный порог для экспериментов с RC ladder.
# Отдельное имя используется для читаемости соответствующего пайплайна.
PHASE_FILTER_MAG: float = 0.05


# Константа 2π для расчёта угловой частоты ω = 2πf.
TWO_PI: float = 2.0 * math.pi